"""E2: first look at one month on the ACCOUNT graph (before entity grouping): size, hubs with on-ledger roles,
tail fits, and a backbone prototype page. Writes docs/graph-first-look-<month>-tables.md and
report/graph_proto.html (self-contained: JSON and the vendored libraries inline).
"""

import json
import logging
import math
import time
from pathlib import Path

import numpy as np

import tails
from common import ALL, RLUSD, Paths, Timer, asset_label, month_bounds, peak_rss_mb, q
from load import load_month
from views import edge_size, layout, sig

log = logging.getLogger("graph")
ROOT = Path(__file__).resolve().parent.parent
TOP = 50


def roles(con, p: Paths, month: str) -> tuple[dict, set, dict]:
    _, d1 = month_bounds(month)
    edges = q(p.part("transfer_edges_monthly", month))
    pools = dict(con.execute(f"""SELECT pool, any_value(asset1 || ' / ' || asset2) FROM read_parquet(
        {q(p.silver / 'amm_events' / 'month=*' / '*.parquet')}) WHERE close_time < DATE '{d1}' GROUP BY 1""").fetchall())
    issuers = dict(con.execute(f"""SELECT split_part(asset, '.', 2), count(DISTINCT asset) FROM read_parquet({edges})
        WHERE asset NOT IN ('XRP', 'MPT') GROUP BY 1""").fetchall())
    dt = p.part("dest_tag_monthly", month)
    tagged = dict(con.execute(f"SELECT account, distinct_tags FROM read_parquet({q(dt)})").fetchall()) if dt.exists() else {}
    cust = {a: (s, tagged[a]) for a, s in con.execute(f"""SELECT to_account, sum(n_tagged)::DOUBLE / sum(n_transfers)
        FROM read_parquet({edges}) GROUP BY 1 HAVING sum(n_transfers) >= 20""").fetchall() if a in tagged and s >= 0.9}
    return pools, issuers, cust


def run(con, p: Paths, month: str) -> None:
    t0 = time.time()
    pools, issuers, cust = roles(con, p, month)
    lines = [f"# Transfer graph first look, {month} (account level, generated by `graph/run.py firstlook`)", ""]
    sizes, measured, fits = [], [], []
    proto = None
    for asset in ("XRP", RLUSD, ALL):
        lab = asset_label(asset)
        with Timer(f"firstlook {month} {lab}") as tm:
            mg = load_month(con, p, month, asset, level="account")
            g = mg.to_igraph()
        load_s, load_mb = tm.seconds, peak_rss_mb()
        t = time.time()
        nv = len(mg.names)
        w = np.nan_to_num(mg.weight, nan=0.0)
        in_deg, out_deg = np.asarray(g.degree(mode="in")), np.asarray(g.degree(mode="out"))
        in_n = np.bincount(mg.dst, weights=mg.n, minlength=nv)
        out_n = np.bincount(mg.src, weights=mg.n, minlength=nv)
        in_w = np.bincount(mg.dst, weights=w, minlength=nv)
        out_w = np.bincount(mg.src, weights=w, minlength=nv)
        pr = np.asarray(g.pagerank(directed=True, damping=0.85, weights="w"))
        wcc = g.connected_components(mode="weak")
        giant = max(wcc.sizes()) / nv
        top = list(np.lexsort((np.arange(nv), -pr))[:TOP])
        for arr in (in_n, out_n):
            top += [v for v in np.lexsort((np.arange(nv), -arr))[:TOP] if v not in top]
        # bot pair: one counterparty takes >= 50% of out_n and the reverse edge exists
        pairs = set(zip(mg.src.tolist(), mg.dst.tolist()))
        best = {}
        for s_, d_, n_ in zip(mg.src.tolist(), mg.dst.tolist(), mg.n.tolist()):
            if s_ not in best or n_ > best[s_][1]:
                best[s_] = (d_, n_)
        rows, counts = [], {}
        for v in top:
            a = mg.names[v]
            if a in pools:
                role, ev = "AMM pool", pools[a][:40]
            elif a in issuers:
                role, ev = "issuer", f"{issuers[a]} token(s) moved"
            elif a in cust:
                role, ev = "likely custodial", f"{cust[a][0]:.0%} tagged, {cust[a][1]:,} tags"
            elif v in best and best[v][1] >= 0.5 * out_n[v] and (best[v][0], v) in pairs:
                role, ev = "bot pair", f"{best[v][1] / out_n[v]:.0%} of sends to {mg.names[best[v][0]][:8]}, which pays back"
            else:
                role, ev = "unknown", ""
            if v in top[:TOP]:
                counts[role] = counts.get(role, 0) + 1
            rows.append((a, role, ev, int(in_deg[v]), int(out_deg[v]), int(in_n[v]), int(out_n[v]),
                         float(in_w[v]), float(out_w[v]), float(pr[v])))
        fin, fout = tails.fit(in_deg[in_deg > 0], True), tails.fit(out_deg[out_deg > 0], True)
        fval = tails.fit(mg.value, False) if asset != ALL else {}
        sizes.append((lab, nv, len(mg.src), int(mg.n.sum()), giant))
        fits.append((lab, fin, fout, fval))
        measured.append((lab, load_s, load_mb, time.time() - t, peak_rss_mb()))
        unit = "transfers" if asset == ALL else lab.split("-")[0]
        lines += [f"## Top 20 hubs by PageRank: {lab}", "",
                  f"| Account | Role | Evidence | In-deg | Out-deg | In transfers | Out transfers | In ({unit}) | Out ({unit}) | PageRank |",
                  "|---|---|---|---:|---:|---:|---:|---:|---:|---:|"]
        for r in rows[:20]:
            lines.append(f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]:,} | {r[4]:,} | {r[5]:,} | {r[6]:,} | "
                         f"{r[7]:,.0f} | {r[8]:,.0f} | {r[9]:.4f} |")
        lines += ["", f"Roles among the top {TOP} by PageRank: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())), ""]
        if asset == "XRP":
            proto = backbone(mg, w, {r[0]: r[1] for r in rows}, month)

    lines[2:2] = ["## Graph size", "", "| Asset | Accounts | Edges | Transfers | Largest weak component |",
                  "|---|---:|---:|---:|---:|"] + [f"| {a} | {b:,} | {c:,} | {d:,} | {e:.1%} |" for a, b, c, d, e in sizes] + [
        "", "## Tail fits (alpha is the density exponent; the Pareto index of the CCDF is alpha - 1)", "",
        "| Asset | In-degree alpha (xmin, tail n) | Out-degree alpha (xmin, tail n) | Edge value alpha (xmin) | Pareto index in / out | R, p vs lognormal (in-degree) |",
        "|---|---|---|---|---|---|"] + [
        f"| {a} | {fi['alpha']:.3f} ({fi['xmin']:,.0f}, {fi['n_tail']:,}) | {fo['alpha']:.3f} ({fo['xmin']:,.0f}, {fo['n_tail']:,}) | "
        + (f"{fv['alpha']:.3f} ({fv['xmin']:,.4g})" if fv.get("alpha") else "-")
        + f" | {fi['alpha'] - 1:.2f} / {fo['alpha'] - 1:.2f} | "
        + (f"{fi['R_lognormal']:.2f}, {fi['p_lognormal']:.3f}" if fi.get("R_lognormal") is not None else "-") + " |"
        for a, fi, fo, fv in fits] + [
        "", "## Measured cost", "", "| Asset | Load s | RSS after load MB | Metrics s | Peak RSS MB |", "|---|---:|---:|---:|---:|"] + [
        f"| {a} | {b:.1f} | {c:,} | {d:.1f} | {e:,} |" for a, b, c, d, e in measured] + [""]
    out = ROOT / "docs" / f"graph-first-look-{month}-tables.md"
    out.write_text("\n".join(lines))
    log.info("firstlook %s: wrote %s and %s in %.1f s", month, out, proto, time.time() - t0)


def backbone(mg, w, role_of: dict, month: str) -> Path:
    nv = len(mg.names)
    wd = np.bincount(mg.src, weights=w, minlength=nv) + np.bincount(mg.dst, weights=w, minlength=nv)
    sel = sorted(np.lexsort((np.arange(nv), -wd))[:300].tolist())
    pos = {v: i for i, v in enumerate(sel)}
    m = np.isin(mg.src, sel) & np.isin(mg.dst, sel)
    es, ed, ew, en = mg.src[m], mg.dst[m], w[m], mg.n[m]
    if len(es) > 20_000:
        k = np.sort(np.lexsort((np.arange(len(ew)), -ew))[:20_000])
        es, ed, ew, en = es[k], ed[k], ew[k], en[k]
    start = [(math.cos(2 * math.pi * i / len(sel)), math.sin(2 * math.pi * i / len(sel))) for i in range(len(sel))]
    xy = layout(len(sel), [(pos[int(a)], pos[int(b)]) for a, b in zip(es, ed)], ew.tolist(), start)
    top = wd[sel].max() or 1
    nodes = [{"key": str(mg.names[v]), "attributes": {"x": sig(xy[i][0]), "y": sig(xy[i][1]),
              "size": sig(2 + 18 * math.sqrt(wd[v] / top)), "role": role_of.get(mg.names[v], "unranked"),
              "label": f"{mg.names[v][:8]} · {role_of.get(mg.names[v], '')}".rstrip(" ·"), "wd": sig(wd[v])}}
             for i, v in enumerate(sel)]
    sz = edge_size(ew)
    edges = [{"key": f"{mg.names[a]}>{mg.names[b]}", "source": str(mg.names[a]), "target": str(mg.names[b]),
              "attributes": {"size": sig(s), "n": int(k), "value": sig(x)}} for a, b, x, k, s in zip(es, ed, ew, en, sz)]
    keys = {"AMM pool": "amm_pool", "likely custodial": "likely_custodial"}  # the page's role keys
    for nd in nodes:
        nd["attributes"]["role"] = keys.get(nd["attributes"]["role"], nd["attributes"]["role"])
    data = {"attributes": {"month": month, "asset": "XRP", "kind": "backbone"}, "options": {"type": "directed"},
            "nodes": nodes, "edges": edges}
    vendor = ROOT / "report" / "vendor"
    html = (ROOT / "report" / "graph.html").read_text()  # same page, data and libraries inline
    note = (f"Prototype: XRP backbone for {month} at ACCOUNT level (before entity grouping), "
            f"top 300 accounts by value moved. Colour = role from on-ledger evidence; grey = unranked or unknown.")
    inline = (f"<script>{(vendor / 'graphology.umd.min.js').read_text()}</script>\n"
              f"<script>{(vendor / 'sigma.min.js').read_text()}</script>\n"
              f"<script>window.INLINE_GRAPH = {json.dumps(data, separators=(',', ':'))};"
              f"window.INLINE_NOTE = {json.dumps(note)};</script>")
    html = html.replace('<script src="vendor/graphology.umd.min.js"></script>\n<script src="vendor/sigma.min.js"></script>', inline)
    out = ROOT / "report" / "graph_proto.html"
    out.write_text(html)
    return out
